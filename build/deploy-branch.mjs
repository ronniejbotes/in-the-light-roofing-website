/**
 * Rebuild the `deploy` branch and push it, in one command.
 *
 *   npm run deploy
 *
 * The deploy branch holds the finished site at its root, so a Git deployment
 * (Hostinger's Deployments panel, or anything else that clones a branch into a
 * web root) can point straight at it. main stays as it is: mirror/ plus the
 * fixes in overrides/, which are only combined at publish time.
 *
 * Never edit the deploy branch by hand. Edit mirror/ or overrides/ on main and
 * run this; anything committed on deploy directly is overwritten by the next
 * run without warning.
 *
 * WHY A WORKTREE AT C:\dwt (or /tmp/dwt)
 * --------------------------------------
 * The tree is ~1,760 files deep inside wp-content/plugins/..., and several
 * paths are long enough that `git add` fails with "Filename too long" if the
 * worktree lives under a deep directory. A short path is not tidiness, it is
 * the difference between this working and not. core.longpaths is set as well.
 *
 * The worktree is kept between runs so a redeploy only copies changed files.
 */
import { execFileSync } from 'node:child_process'
import { cp, rm, readdir, writeFile, mkdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PUB = join(ROOT, 'publish')
const BRANCH = 'deploy'
const WT = process.env.DEPLOY_WT || (process.platform === 'win32' ? 'C:\\dwt' : '/tmp/dwt')

const git = (args, cwd = ROOT) =>
  execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()

function gitLoud(args, cwd = ROOT) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: 'inherit' })
}

async function main() {
  // 1. Build the site. publish.mjs wipes and rewrites publish/ itself.
  console.log('> building publish/ ...')
  execFileSync(process.execPath, [join(ROOT, 'build', 'publish.mjs')], { cwd: ROOT, stdio: 'inherit' })
  if (!existsSync(PUB)) throw new Error('publish/ was not produced')

  // 2. Long paths, or `git add` dies partway through wp-content/plugins.
  try { git(['config', 'core.longpaths', 'true']) } catch { /* not fatal */ }

  // 3. A worktree holding the deploy branch, at a short path.
  const known = (() => { try { return git(['worktree', 'list']) } catch { return '' } })()
  if (!existsSync(WT) || !known.includes(WT.replace(/\\/g, '/'))) {
    try { git(['worktree', 'prune']) } catch { /* fine */ }
    await rm(WT, { recursive: true, force: true })
    const hasBranch = (() => {
      try { git(['rev-parse', '--verify', BRANCH]); return true } catch { return false }
    })()
    console.log(`> creating worktree at ${WT} (${hasBranch ? 'existing' : 'new'} branch ${BRANCH})`)
    gitLoud(hasBranch
      ? ['worktree', 'add', WT, BRANCH]
      : ['worktree', 'add', '--orphan', '-b', BRANCH, WT])
  }

  // 4. Replace the worktree contents with the freshly built site. Everything
  //    except .git goes, so a page deleted upstream is deleted here too --
  //    a copy-over-the-top would leave it live for ever.
  for (const e of await readdir(WT)) {
    if (e === '.git') continue
    await rm(join(WT, e), { recursive: true, force: true })
  }
  await cp(PUB, WT, { recursive: true })

  // Built artifact: check it out byte-for-byte. Without this git rewrites line
  // endings on the server's checkout, which is how a .htaccess grows CRLF.
  await writeFile(join(WT, '.gitattributes'),
    '# This branch is a built artifact: store and check out every byte verbatim.\n* -text\n')

  // The branch carries no .gitignore of its own, because everything on it is
  // generated and there is nothing to ignore *here* -- this worktree only ever
  // holds a copy of publish/. But the branch does not stay in this worktree.
  // Check `deploy` out in the repo working directory (GitHub Desktop will, from
  // the branch menu) and git suddenly sees node_modules/, dist/, .vite-out/ and
  // .routes.json as 3,000-odd untracked files, all pre-ticked and one click from
  // being committed onto the branch Hostinger clones into the web root.
  // main's .gitignore covers them; deploy needs its own copy of that cover.
  await writeFile(join(WT, '.gitignore'),
    '# This branch is generated by `npm run deploy` and holds the built site only.\n'
    + '# These are main\'s working files. They are listed here so that checking this\n'
    + '# branch out in the repo directory does not offer them up to be committed.\n'
    + 'node_modules/\ndist/\npublish/\n.vite-out/\n.out-*/\n.routes.json\n'
    + 'mirror/\noverrides/\nbuild/\ntools/\nsrc/\nstatic/\ncontent/\n'
    + '*.log\n.DS_Store\nThumbs.db\n')

  // 5. Commit and push, if anything actually changed.
  gitLoud(['add', '-A'], WT)
  const staged = git(['diff', '--cached', '--name-only'], WT)
  if (!staged) {
    console.log('\n> deploy branch already matches publish/ -- nothing to push.\n')
    return
  }
  const count = staged.split('\n').filter(Boolean).length
  git(['commit', '-q', '-m', `Deploy build: ${count} file${count === 1 ? '' : 's'} changed\n\n`
    + 'Generated by `npm run deploy` from mirror/ + overrides/ on main.\n'
    + 'Do not edit this branch by hand -- the next run overwrites it.'], WT)
  console.log(`> pushing ${count} changed file${count === 1 ? '' : 's'} ...`)
  gitLoud(['push', '-u', 'origin', BRANCH], WT)
  console.log('\n> pushed. Hit Redeploy in Hostinger -> Deployments.\n')
}

main().catch((e) => {
  console.error('\ndeploy failed:', e.message)
  process.exit(1)
})
